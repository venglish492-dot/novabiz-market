// Generates src/features/socials/brand-icons.generated.ts from the simple-icons
// package (CC0). Only the icons VYBE offers are extracted so the client bundle
// never ships the whole icon set. Run: npm run icons:generate
import * as icons from 'simple-icons';

const WANTED = {
  discord: 'siDiscord', github: 'siGithub', youtube: 'siYoutube', tiktok: 'siTiktok', instagram: 'siInstagram',
  x: 'siX', twitch: 'siTwitch', spotify: 'siSpotify', soundcloud: 'siSoundcloud', telegram: 'siTelegram',
  reddit: 'siReddit', steam: 'siSteam', roblox: 'siRoblox', playstation: 'siPlaystation', snapchat: 'siSnapchat',
  kick: 'siKick', pinterest: 'siPinterest', bluesky: 'siBluesky', threads: 'siThreads', patreon: 'siPatreon',
  kofi: 'siKofi', behance: 'siBehance', dribbble: 'siDribbble', vimeo: 'siVimeo', applemusic: 'siApplemusic',
  facebook: 'siFacebook', whatsapp: 'siWhatsapp', signal: 'siSignal', mastodon: 'siMastodon', bandcamp: 'siBandcamp',
  letterboxd: 'siLetterboxd', buymeacoffee: 'siBuymeacoffee', epicgames: 'siEpicgames', battlenet: 'siBattledotnet',
  valorant: 'siValorant', osu: 'siOsu', cashapp: 'siCashapp', paypal: 'siPaypal', substack: 'siSubstack',
  medium: 'siMedium', gitlab: 'siGitlab', lastfm: 'siLastdotfm', deezer: 'siDeezer', figma: 'siFigma',
};

const lines = [
  '// Generated by scripts/generate-brand-icons.mjs from simple-icons (CC0-1.0). Do not edit by hand.',
  '// Brand marks remain trademarks of their owners and are used only to label links.',
  'export const BRAND_ICONS: Record<string, { title: string; hex: string; path: string }> = {',
];
for (const [key, name] of Object.entries(WANTED)) {
  const icon = icons[name];
  if (!icon) throw new Error(`Missing icon ${name}`);
  lines.push(`  ${JSON.stringify(key)}: { title: ${JSON.stringify(icon.title)}, hex: '#${icon.hex}', path: ${JSON.stringify(icon.path)} },`);
}
lines.push('};', '');
process.stdout.write(lines.join('\n'));
