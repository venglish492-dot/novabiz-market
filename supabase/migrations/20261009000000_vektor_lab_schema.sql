-- ---------------------------------------------------------------------
-- Ownership, reviews and rating aggregation
-- ---------------------------------------------------------------------

create or replace function public.user_owns_product(p_product_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.entitlements
    where user_id = auth.uid() and product_id = p_product_id and revoked_at is null
  );
$$;

-- Reviews: identity, ownership flag and moderation state are set here,
-- not by the client.
create or replace function public.prepare_review()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    new.verified_purchase := exists (
      select 1 from public.entitlements
      where user_id = new.user_id and product_id = new.product_id and revoked_at is null
    );
    if coalesce(auth.role(), '') <> 'service_role' then
      new.status := 'pending';
      new.moderated_by := null;
      new.moderated_at := null;
    end if;
  end if;
  return new;
end;
$$;

create trigger reviews_prepare before insert on public.reviews
  for each row execute function public.prepare_review();

create or replace function public.refresh_product_rating()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  target uuid := coalesce(new.product_id, old.product_id);
begin
  update public.products p
  set rating_average = stats.avg_rating,
      rating_count = stats.cnt
  from (
    select round(avg(rating)::numeric, 2) as avg_rating, count(*)::int as cnt
    from public.reviews
    where product_id = target and status = 'approved' and verified_purchase
  ) stats
  where p.id = target;
  return null;
end;
$$;

create trigger reviews_rating after insert or update or delete on public.reviews
  for each row execute function public.refresh_product_rating();

create or replace function public.count_download()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'success' and new.product_id is not null then
    update public.products set download_count = download_count + 1 where id = new.product_id;
  end if;
  return null;
end;
$$;

