-- =====================================================================
-- Vektor Lab — core schema
--
-- Security model
--   * Row Level Security is enabled on every table.
--   * Public visitors can read published catalog content only.
--   * Customers can read their own profile, orders, entitlements and
--     downloads, manage their own cart/wishlist, and review products they own.
--   * Orders, payments, entitlements and downloads are written only by the
--     server using the service-role key, after explicit verification.
--   * Roles live in public.profiles and cannot be changed by the user.
--   * Paid files live in a private storage bucket; buyers receive short-lived
--     signed URLs generated by the server after an ownership check.
-- =====================================================================

