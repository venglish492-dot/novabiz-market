-- ---------------------------------------------------------------------
-- Order fulfilment (called by the server with the service role)
-- Atomic and idempotent: a second call for a paid order is a no-op.
-- ---------------------------------------------------------------------

create or replace function public.fulfil_order(
  p_order_id uuid,
  p_provider text,
  p_provider_payment_id text default null
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
begin
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'Order % not found', p_order_id;
  end if;

  if v_order.status = 'paid' then
    return false;
  end if;

  if v_order.status not in ('pending', 'payment_pending', 'failed') then
    raise exception 'Order % cannot be fulfilled from status %', p_order_id, v_order.status;
  end if;

  update public.orders
  set status = 'paid', paid_at = now(), provider = coalesce(p_provider, provider)
  where id = p_order_id;

  update public.payments
  set status = 'succeeded', provider_payment_id = coalesce(p_provider_payment_id, provider_payment_id)
  where order_id = p_order_id and provider = p_provider and status in ('created', 'pending', 'failed');

  insert into public.entitlements (user_id, product_id, order_id, license_tier)
  select v_order.user_id, oi.product_id, v_order.id, oi.license_tier
  from public.order_items oi
  where oi.order_id = v_order.id
  on conflict (user_id, product_id, order_id) do nothing;

  -- Bundles grant access to their included products as well.
  insert into public.entitlements (user_id, product_id, order_id, license_tier)
  select v_order.user_id, bi.product_id, v_order.id, oi.license_tier
  from public.order_items oi
  join public.bundle_items bi on bi.bundle_id = oi.product_id
  where oi.order_id = v_order.id
  on conflict (user_id, product_id, order_id) do nothing;

  if v_order.coupon_id is not null then
    insert into public.coupon_redemptions (coupon_id, user_id, order_id)
    values (v_order.coupon_id, v_order.user_id, v_order.id)
    on conflict (order_id) do nothing;
    update public.coupons set times_used = times_used + 1 where id = v_order.coupon_id;
  end if;

  delete from public.cart_items
  where user_id = v_order.user_id
    and product_id in (select product_id from public.order_items where order_id = v_order.id);

  return true;
end;
$$;

create or replace function public.mark_order_refunded(p_order_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.orders set status = 'refunded', refunded_at = now()
  where id = p_order_id and status = 'paid';
  update public.payments set status = 'refunded' where order_id = p_order_id and status = 'succeeded';
  update public.entitlements set revoked_at = now() where order_id = p_order_id and revoked_at is null;
end;
$$;

revoke execute on function public.fulfil_order(uuid, text, text) from public, anon, authenticated;
revoke execute on function public.mark_order_refunded(uuid) from public, anon, authenticated;

